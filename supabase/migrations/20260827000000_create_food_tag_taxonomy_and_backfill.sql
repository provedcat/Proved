-- Normalized, auditable food taxonomy for the existing cat and dog catalogues.
-- This migration is intentionally conservative: an absent/ambiguous claim creates
-- a review item instead of a low-confidence searchable tag.

create table if not exists public.food_tags (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug = lower(slug) and slug ~ '^[a-z0-9_]+$'),
  label_ko text not null,
  label_en text not null,
  category text not null check (category in (
    'processing_method', 'preparation_type', 'life_stage',
    'ingredient_condition', 'protein_source', 'product_class', 'management_purpose'
  )),
  description text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (category, slug)
);

create table if not exists public.feed_food_tags (
  feed_id uuid not null references public.feeds(id) on delete cascade,
  tag_id bigint not null references public.food_tags(id) on delete restrict,
  source text not null check (source in (
    'existing_field', 'manufacturer_claim', 'ingredient_derived',
    'product_name_derived', 'manual', 'migration'
  )),
  confidence text not null check (confidence in ('high', 'medium')),
  reason text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (feed_id, tag_id)
);

create table if not exists public.dog_feed_food_tags (
  dog_feed_id uuid not null references public.dog_feeds(id) on delete cascade,
  tag_id bigint not null references public.food_tags(id) on delete restrict,
  source text not null check (source in (
    'existing_field', 'manufacturer_claim', 'ingredient_derived',
    'product_name_derived', 'manual', 'migration'
  )),
  confidence text not null check (confidence in ('high', 'medium')),
  reason text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (dog_feed_id, tag_id)
);

create table if not exists public.food_tag_review_queue (
  id bigint generated by default as identity primary key,
  species text not null check (species in ('cat', 'dog')),
  product_id uuid not null,
  issue_type text not null check (issue_type in (
    'unknown_processing_method', 'unknown_life_stage', 'ambiguous_veterinary_diet',
    'ambiguous_chicken_free', 'ambiguous_grain_free', 'unknown_protein_source',
    'conflicting_evidence'
  )),
  reason text not null,
  evidence jsonb not null default '{}'::jsonb,
  status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  unique (species, product_id, issue_type)
);

create index if not exists food_tags_category_active_sort_idx
  on public.food_tags(category, is_active, sort_order, id);
create index if not exists feed_food_tags_tag_feed_idx on public.feed_food_tags(tag_id, feed_id);
create index if not exists dog_feed_food_tags_tag_feed_idx on public.dog_feed_food_tags(tag_id, dog_feed_id);
create index if not exists food_tag_review_queue_open_idx
  on public.food_tag_review_queue(species, issue_type, product_id) where status = 'open';

