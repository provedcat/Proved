-- Read-only validation/query surface. The category array supports AND across axes
-- without adding denormalized columns to either product table.
create or replace view public.food_tag_distribution as
select 'cat'::text species, t.category, t.slug, t.label_ko, count(*)::bigint product_count
from public.feed_food_tags x join public.food_tags t on t.id=x.tag_id group by t.category,t.slug,t.label_ko
union all
select 'dog', t.category, t.slug, t.label_ko, count(*)::bigint
from public.dog_feed_food_tags x join public.food_tags t on t.id=x.tag_id group by t.category,t.slug,t.label_ko;

